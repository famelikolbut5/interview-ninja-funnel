CREATE TABLE participants (
    user_id BIGINT PRIMARY KEY,
    started_at DOUBLE PRECISION NOT NULL,
    registered_at DOUBLE PRECISION,
    phone_number TEXT,
    source_key TEXT,
    utm_source TEXT,
    utm_medium TEXT,
    utm_campaign TEXT,
    utm_content TEXT,
    utm_term TEXT
);

CREATE TABLE jobs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES participants (user_id),
    chat_id BIGINT NOT NULL,
    step SMALLINT NOT NULL CHECK (step IN (1, 2)),
    text TEXT NOT NULL,
    due_at DOUBLE PRECISION NOT NULL,
    available_at DOUBLE PRECISION NOT NULL,
    attempts INTEGER NOT NULL DEFAULT 0 CHECK (attempts >= 0),
    sent_at DOUBLE PRECISION,
    failed_at DOUBLE PRECISION,
    UNIQUE (user_id, step),
    CHECK (sent_at IS NULL OR failed_at IS NULL)
);

CREATE INDEX pending_jobs ON jobs (available_at, id)
    WHERE sent_at IS NULL AND failed_at IS NULL;
